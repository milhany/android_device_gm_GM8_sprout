#!/usr/bin/env python3
"""Compare selected GM8 UAPI layouts with real ARM/ARM64 compiler targets.

This is a header-level audit, not proof that proprietary binaries or drivers
behave correctly. It never loads a driver or communicates with a phone.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import tempfile

GROUPS = {
    "kgsl": "include/uapi/linux/msm_kgsl.h",
    "qseecom": "include/uapi/linux/qseecom.h",
    "camera_v1": "include/uapi/media/msm_camera.h",
    "camera_sensor": "include/uapi/media/msm_cam_sensor.h",
    "camera_sdk": "include/uapi/media/msm_camsensor_sdk.h",
    "camera_isp": "include/uapi/media/msmb_isp.h",
    "camera_subdev": "include/uapi/media/msmb_camera.h",
    "camera_pproc": "include/uapi/media/msmb_pproc.h",
    "vidc_metadata": "include/uapi/media/msm_vidc.h",
    "ion": "drivers/staging/android/uapi/ion.h",
}
TARGETS = {"arm64": "aarch64-linux-gnu", "arm": "armv7a-linux-gnueabihf"}
LEGACY_CAMERA = {
    "camera_v1": "techpack/camera-legacy/include/uapi/media/msm_camera-legacy.h",
    "camera_sensor": "techpack/camera-legacy/include/uapi/media/msm_cam_sensor-legacy.h",
    "camera_sdk": "techpack/camera-legacy/include/uapi/media/msm_camsensor_sdk-legacy.h",
    "camera_isp": "techpack/camera-legacy/include/uapi/media/msmb_isp-legacy.h",
    "camera_subdev": "techpack/camera-legacy/include/uapi/media/msmb_camera-legacy.h",
    "camera_pproc": "techpack/camera-legacy/include/uapi/media/msmb_pproc-legacy.h",
}


def command(args):
    result = subprocess.run([str(x) for x in args], text=True, capture_output=True)
    if result.returncode:
        raise RuntimeError(result.stderr)
    return result.stdout


def stripped(path):
    text = path.read_text()
    text = re.sub(r"/\*.*?\*/|//[^\n]*", "", text, flags=re.S)
    return text.replace("\\\n", " ")


def declarations(path):
    text = stripped(path)
    requests = set(re.findall(r"^\s*#define\s+(\w+)\s+_IO(?:WR|W|R)?\s*\(",
                              text, re.M))
    records = set(re.findall(r"\bstruct\s+(\w+)\s*\{", text))
    return requests, records


def include_tree(root, arch, work):
    (work / "asm").mkdir(parents=True)
    # These are the architecture-generic UAPI forwarding headers normally
    # generated by Kbuild, not stand-in definitions of any audited structure.
    for header in (root / "include/uapi/asm-generic").glob("*.h"):
        (work / "asm" / header.name).write_text(
            f"#include <asm-generic/{header.name}>\n")
    (work / "linux/staging/android").mkdir(parents=True)
    (work / "linux/staging/android/uapi").symlink_to(
        root / "drivers/staging/android/uapi", target_is_directory=True)
    for name in ("ion.h", "msm_ion.h"):
        (work / "linux" / name).symlink_to(root / "drivers/staging/android/uapi" / name)
    # headers_install normally strips internal compiler includes and these
    # annotations. Keep raw audited UAPI files unchanged and supply only the
    # userspace equivalents here; no structure or ioctl is redefined.
    for name in ("compiler.h", "compiler_types.h"):
        (work / "linux" / name).write_text(
            "#define __user\n#define __force\n#define __iomem\n"
            "#define __packed __attribute__((packed))\n"
            "#define __attribute_const__ __attribute__((const))\n")
    # videodev2.h includes libc's sys/time.h in userspace. Use the matching
    # kernel UAPI time structures in this freestanding layout-only probe.
    (work / "sys").mkdir()
    (work / "sys/time.h").write_text("#include <linux/time.h>\n")
    return ["-I", root / "arch" / arch / "include/uapi",
            "-I", root / "techpack/camera-legacy/include/uapi",
            "-I", work, "-I", root / "include/uapi", "-I", root / "include"]


def prelude(root, relative, legacy):
    text = "#include <stddef.h>\n#include <stdint.h>\n"
    if relative == GROUPS["ion"] and legacy:
        text += '#define CONFIG_ION_LEGACY 1\n'
        text += f'#include "{root}/drivers/staging/android/ion/ion_legacy.h"\n'
    else:
        text += f'#include "{root / relative}"\n'
    return text


def probe(clang, root, arch, relative, requests, records, legacy, work):
    source = work / "probe.c"
    prefix = prelude(root, relative, legacy)
    prefix += f'_Static_assert(sizeof(void *) == {8 if arch == "arm64" else 4}, "target pointer width");\n'
    source.write_text(prefix)
    flags = [clang, "--target=" + TARGETS[arch], "-ffreestanding", "-nostdinc",
             "-isystem", command([clang, "-print-resource-dir"]).strip() + "/include",
             "-D__EXPORTED_HEADERS__", *include_tree(root, arch, work)]
    ast = json.loads(command(flags + ["-Xclang", "-ast-dump=json", "-fsyntax-only", source]))
    fields = {}
    aliases = {name: ("ion_old_allocation_data" if legacy and
                     name == "ion_allocation_data" else name) for name in records}
    reverse_aliases = {mapped: name for name, mapped in aliases.items()}

    def walk(node):
        name = node.get("name")
        if node.get("kind") == "RecordDecl" and node.get("completeDefinition") and name in reverse_aliases:
            fields[reverse_aliases[name]] = [item["name"] for item in node.get("inner", [])
                            if item.get("kind") == "FieldDecl" and item.get("name")
                            and not item.get("isBitfield")]
        for child in node.get("inner", []):
            walk(child)
    walk(ast)
    expressions = {}
    for name in sorted(requests):
        mapped = "ION_OLD_IOC_ALLOC" if legacy and name == "ION_IOC_ALLOC" else name
        expressions["ioctl:" + name] = mapped
    for name in sorted(records):
        actual = aliases[name]
        expressions[f"size:{name}"] = f"sizeof(struct {actual})"
        expressions[f"align:{name}"] = f"__alignof__(struct {actual})"
        for field in fields[name]:
            expressions[f"offset:{name}.{field}"] = f"__builtin_offsetof(struct {actual}, {field})"
    source.write_text(prefix + "\nconst unsigned long long gm8_abi[] = {\n" +
                      ",\n".join(expressions.values()) + "\n};\n")
    ir = command(flags + ["-S", "-emit-llvm", "-o", "-", source])
    array = next(line for line in ir.splitlines() if line.startswith("@gm8_abi ="))
    values = [int(value) for value in re.findall(r"i64 (-?\d+)", array)]
    if len(values) != len(expressions):
        raise ValueError("Compiler IR value count differs from requested ABI probes")
    return dict(zip(expressions, values))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--old", type=Path, required=True)
    parser.add_argument("--new", type=Path, required=True)
    parser.add_argument("--clang", default="clang")
    parser.add_argument("--camera-stack", choices=["modern", "legacy"], default="modern")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    old, new = args.old.resolve(), args.new.resolve()
    report = {"compiler": command([args.clang, "--version"]).splitlines()[0],
              "camera_stack": args.camera_stack,
              "scope": "Header ABI only; runtime ioctl implementations, binary call usage, "
                       "secure firmware and HAL functionality are not validated. Only named "
                       "structures, named non-bitfield offsets and ioctl request values are compared; "
                       "general enum values, bitfield layouts and anonymous members are not audited.",
              "header_environment": "Freestanding ARM targets, kernel generic asm forwarding, "
                                    "compiler annotations removed as for UAPI export; sys/time.h "
                                    "uses matching kernel UAPI time structures, not Android libc.",
              "revisions": {label: command(["git", "-C", root, "rev-parse", "HEAD"]).strip()
                            for label, root in [("old", old), ("new", new)]},
              "groups": {}}
    with tempfile.TemporaryDirectory(prefix="gm8-uapi-") as directory:
        for group, relative in GROUPS.items():
            new_relative = LEGACY_CAMERA.get(group, relative) if args.camera_stack == "legacy" else relative
            old_req, old_rec = declarations(old / relative)
            new_req, new_rec = declarations(new / new_relative)
            if group == "ion":
                new_req, new_rec = declarations(new / "drivers/staging/android/ion/ion_legacy.h")
                new_req.add("ION_IOC_ALLOC")
                new_rec.add("ion_allocation_data")
                new_req.discard("ION_OLD_IOC_ALLOC")
                new_rec.discard("ion_old_allocation_data")
            requests, records = old_req & new_req, old_rec & new_rec
            entry = {"headers": {"old": relative, "new": new_relative},
                     "top_level_header_sha256": {label: hashlib.sha256((root / path).read_bytes()).hexdigest()
                                                  for label, root, path in [("old", old, relative), ("new", new, new_relative)]},
                     "old_requests_not_in_new_headers": sorted(old_req - new_req),
                     "old_structures_not_in_new_headers": sorted(old_rec - new_rec),
                     "common_requests": sorted(requests), "targets": {}}
            for arch in TARGETS:
                snapshots = {}
                for label, root in [("old", old), ("new", new)]:
                    work = Path(directory) / group / arch / label
                    work.mkdir(parents=True)
                    path = relative if label == "old" else new_relative
                    snapshots[label] = probe(args.clang, root, arch, path, requests,
                                             records, group == "ion" and label == "new", work)
                keys = snapshots["old"].keys() & snapshots["new"].keys()
                changed = {key: {label: snapshots[label][key] for label in snapshots}
                           for key in sorted(keys) if snapshots["old"][key] != snapshots["new"][key]}
                entry["targets"][arch] = {"compared": len(keys), "differences": changed,
                                           "removed_probe_keys": sorted(snapshots["old"].keys() - snapshots["new"].keys()),
                                           "new_probe_keys": sorted(snapshots["new"].keys() - snapshots["old"].keys()),
                                           "probe_values_sha256": {
                                               label: hashlib.sha256(json.dumps(values, sort_keys=True).encode()).hexdigest()
                                               for label, values in snapshots.items()},
                                           "request_values": {
                                               label: {key: value for key, value in values.items() if key.startswith("ioctl:")}
                                               for label, values in snapshots.items()}}
                print(f"{group}/{arch}: {len(keys)} probes, {len(changed)} differences")
            report["groups"][group] = entry
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, indent=2) + "\n")
    print(f"Report: {args.output}")


if __name__ == "__main__":
    main()
